import { chromium } from 'playwright';

const browser = await chromium.launch({ args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1632, height: 900 } });
const errors = [];
page.on('console', (message) => { if (message.type() === 'error') errors.push(`console:${message.text()}`); });
page.on('pageerror', (error) => errors.push(`page:${error.message}`));
await page.goto('http://localhost:4180/', { waitUntil: 'domcontentloaded', timeout: 30000 });
await page.locator('.cm-content').first().waitFor({ state: 'visible', timeout: 30000 });
const workspace = page.locator('[aria-label="Zoom in canvas"]').locator('..').locator('..');
const canvas = page.locator('canvas').first();
const before = await canvas.evaluate((node) => node.parentElement?.getAttribute('style') || '');
await page.getByRole('button', { name: 'Zoom in canvas' }).click();
await page.waitForTimeout(100);
const zoomText = await canvas.evaluate((node) => node.parentElement?.getAttribute('style') || '');
await workspace.hover();
await page.mouse.wheel(0, -400);
await page.waitForTimeout(100);
const afterZoom = await canvas.evaluate((node) => node.parentElement?.getAttribute('style') || '');
await page.mouse.move(820, 430);
await page.mouse.down();
await page.mouse.move(900, 470, { steps: 3 });
await page.mouse.up();
const afterPan = await canvas.evaluate((node) => node.parentElement?.getAttribute('style') || '');
await page.getByRole('tab', { name: 'Animate' }).click();
const testSound = page.getByRole('button', { name: 'Test sound' });
const soundAvailable = await testSound.count() > 0;
if (soundAvailable) await testSound.click();
console.log(JSON.stringify({ before, zoomText, afterZoom, afterPan, soundAvailable, errors }, null, 2));
await browser.close();
if (errors.length || afterZoom === before || before === afterPan || !soundAvailable) process.exit(1);
