import { chromium } from 'playwright';
import { mkdir, readFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';

await mkdir('tests/media-artifacts', { recursive: true });
const browser = await chromium.launch({ args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1632, height: 900 }, acceptDownloads: true });
const errors = [];
page.on('console', (message) => { if (message.type() === 'error') errors.push(`console: ${message.text()}`); });
page.on('pageerror', (error) => errors.push(`page: ${error.message}`));
await page.goto('http://localhost:4180/', { waitUntil: 'domcontentloaded', timeout: 30000 });
await page.locator('.cm-content').first().waitFor({ state: 'visible', timeout: 30000 });
await page.waitForTimeout(500);
const editor = page.locator('.cm-content').first();
await editor.click();
await page.keyboard.press('Control+A');
await page.keyboard.type('const mp4 = true;\nconsole.log(mp4);');
await page.waitForTimeout(500);
await page.getByRole('tab', { name: 'Export' }).click();
await page.waitForTimeout(250);
await page.getByRole('button', { name: /^MP4$/i }).click();
const downloadPromise = page.waitForEvent('download', { timeout: 300000 });
await page.getByRole('button', { name: /^Export MP4$/i }).click();
const download = await downloadPromise;
const target = 'tests/media-artifacts/mp4-only.mp4';
await download.saveAs(target);
const bytes = await readFile(target);
const probe = spawnSync('ffprobe', ['-v', 'error', '-show_entries', 'format=format_name,duration,size:stream=index,codec_name,codec_type,width,height,avg_frame_rate,nb_frames', '-of', 'json', target], { encoding: 'utf8' });
console.log(JSON.stringify({ bytes: bytes.length, signature: bytes.subarray(0, 16).toString('latin1'), ffprobeExit: probe.status, ffprobeStdout: probe.stdout, ffprobeStderr: probe.stderr, errors, status: (await page.locator('body').innerText()).slice(-400) }, null, 2));
await browser.close();
if (errors.length || probe.status !== 0) process.exit(1);
